"""Проверка относительных путей, пришедших со второго компьютера.

Проводник записывает файлы сам, но имена в FILEGROUPDESCRIPTORW строим мы -
и это единственное место в этой функции, где безопасность целиком наша. Ни
один пир, даже доверенный, не имеет права указать, куда писать.

Отвергается МАНИФЕСТ ЦЕЛИКОМ, а не отдельная запись (см. sanitize_manifest):
пользователь, получивший девять файлов из десяти, об этом не узнает, а честный
отказ он увидит.

Нормализация Unicode идёт ПЕРЕД остальными проверками, и это не косметика.
NFC - каноническая форма: она не разворачивает совместимые варианты вроде
полноширинной точки (для этого нужен NFKC, а не NFC - мы сознательно
остаёмся на NFC, см. sanitize_relative_path), но она может и УДЛИНИТЬ
строку в единицах UTF-16. Например, U+0344 (COMBINING GREEK DIALYTIKA
TONOS) исключён из повторной композиции: после NFC он становится двумя
отдельными знаками вместо одного. Если бы потолок длины мерили до
нормализации, такое имя проскочило бы мимо него.

Правила здесь - надмножество и для macOS тоже. Ослаблять их под другую
платформу незачем: запрет лишнего имени никого не ломает, а разные правила на
двух концах ломают ровно то, что должно совпадать.
"""

from __future__ import annotations

import unicodedata

#: cFileName - это WCHAR[260], то есть 259 значимых единиц UTF-16 плюс ноль.
MAX_PATH_UTF16 = 259

#: Глубина, за которой дерево перестаёт быть похожим на копирование файлов.
MAX_DEPTH = 32

_FORBIDDEN_CHARACTERS = frozenset('<>:"|?*')

#: Зарезервированные имена устройств Windows. Помимо классических CON/PRN/
#: AUX/NUL/COMn/LPTn сюда входят:
#: - CONIN$/CONOUT$ - открываются как консольные буферы ввода/вывода, а не
#:   как файлы: запись в "CONOUT$" ничего не создаёт на диске (проверено
#:   через open() - см. §11 спецификации и task-1.2-report.md), и получатель
#:   увидит "успешную" передачу с пропавшим файлом.
#: - COM¹/COM²/COM³/LPT¹/LPT²/LPT³ (надстрочные цифры U+00B9/U+00B2/U+00B3) -
#:   парсер DOS-имён устройств в Windows приравнивает их к COM1/COM2/COM3/
#:   LPT1/LPT2/LPT3: GetFullPathNameW("COM¹") возвращает "\\.\COM¹" - то же
#:   самое устройство, что и у "COM1" - измерено напрямую, а не выведено из
#:   FileNotFoundError при отсутствующем порте (см. §11 спецификации и
#:   task-1.2-report.md). .upper() эти символы не трогает (это не буквы),
#:   поэтому их нужно перечислить отдельно, а не полагаться на
#:   регистронезависимость.
_RESERVED_STEMS = frozenset(
    {"CON", "PRN", "AUX", "NUL", "CONIN$", "CONOUT$"}
    | {f"COM{digit}" for digit in "123456789"}
    | {f"LPT{digit}" for digit in "123456789"}
    | {"COM¹", "COM²", "COM³", "LPT¹", "LPT²", "LPT³"}
)

#: Управление направлением текста (bidi overrides/isolates, U+202A-U+202E и
#: U+2066-U+2069). Они не появляются в обычном тексте ни на одном языке -
#: направление арабского или иврита несёт сам алфавит, а не эти управляющие
#: знаки - зато ими собирают классический троян "invoice" + RLO + "gpj.exe",
#: который Проводник рисует как "invoiceexe.jpg" (см. §11 спецификации,
#: измерено через open() в task-1.2-report.md). Диапазон, а не одиночные
#: символы, и НЕ "весь non-ASCII": блокировать обычные буквы недопустимо,
#: этой функцией пользуются настоящие люди.
_BIDI_CONTROL_CHARACTERS = frozenset(
    chr(codepoint) for codepoint in (*range(0x202A, 0x202F), *range(0x2066, 0x206A))
)

#: Невидимые знаки, у которых нет легитимной роли в написании текста: мягкий
#: перенос (U+00AD, влияет только на перенос строки), нулевая ширина - пробел
#: (U+200B), word joiner (U+2060) и метка порядка байт (U+FEFF). Ничего не
#: меняют в форме соседних букв, только остаются в имени: "photo.jpg" и
#: "photo<ZWSP>.jpg" выглядят одинаково, а на диске это две разные записи.
#:
#: U+200C (ZWNJ) и U+200D (ZWJ) сюда СОЗНАТЕЛЬНО не входят, хотя формально
#: тоже нулевой ширины: в отличие от четырёх выше, они меняют форму соседних
#: символов, а не только зазор между ними - это и есть причина, по которой
#: их печатают. ZWJ склеивает составные эмодзи (семья, флаг, профессия - имя
#: с ними не собралось бы без ZWJ), ZWNJ обязателен в персидской орфографии
#: и деванагари, а не декоративен. Измерено на этой машине: оба создаются
#: как обычные файлы наравне с ASCII-именем. Раз §11 отвергает манифест
#: целиком, а не отдельную запись, блокировка этой пары означала бы валить
#: весь список из-за одного файла с настоящим, а не поддельным именем -
#: обмен на неё того не стоит.
_INVISIBLE_CHARACTERS = frozenset("\u00ad\u200b\u2060\ufeff")

#: "Нехарактеры" Unicode (U+FDD0-U+FDEF и последние две позиции каждой из 17
#: плоскостей): зарезервированы стандартом именно как непредставимые, ни одно
#: приложение не обязано их где-либо отображать.
_NONCHARACTERS = frozenset(
    chr(codepoint) for codepoint in range(0xFDD0, 0xFDF0)
) | frozenset(
    chr(plane * 0x10000 + offset) for plane in range(0x11) for offset in (0xFFFE, 0xFFFF)
)

_FORBIDDEN_FORMATTING_CHARACTERS = (
    _BIDI_CONTROL_CHARACTERS | _INVISIBLE_CHARACTERS | _NONCHARACTERS
)


class UnsafePath(ValueError):
    """Путь, которого не мог бы прислать исправный второй компьютер."""


def _utf16_units(text: str) -> int:
    """Длина в единицах UTF-16, а не в символах Python.

    Символ вне BMP занимает две единицы, а поле cFileName считает именно их.
    len() здесь соврал бы вдвое в пользу злоумышленника.
    """
    try:
        return len(text.encode("utf-16-le")) // 2
    except UnicodeEncodeError as exc:
        # Одинокий суррогат (например, из json.loads() над испорченным
        # экранированием вида "\ud800" без парной половины - см.
        # clipboard/wire.py) не кодируется в UTF-16 вообще: это не вопрос
        # длины, символа физически не существует. Контракт этой функции -
        # "каноническая форма или UnsafePath", а не необработанное
        # исключение кодека, поэтому дефект превращается в тот же UnsafePath.
        raise UnsafePath("одинокий суррогат в имени") from exc


def sanitize_relative_path(raw: str) -> str:
    """Каноническая относительная форма, либо ``UnsafePath``."""
    if not isinstance(raw, str):
        raise UnsafePath("путь должен быть str")
    if not raw:
        # NB (Task 1.4): эта проверка перекрыта проверкой пустого сегмента в
        # _check_segment. "".split("/") даёт [""], то есть один пустой
        # сегмент, и он ловится там же, где и "Photos//img.jpg". Удалить
        # нужно ОБА места, иначе тест на пустой путь останется зелёным.
        raise UnsafePath("пустой путь")

    # 1. Нормализация Unicode - первым делом, до всех остальных проверок.
    # Именно NFC, не NFKC: коллизии в манифесте (Task 1.3) определены как
    # "совпали после NFC", и NFKC складывал бы разные удалённые имена в один
    # локальный файл сильнее, чем нужно для безопасности.
    text = unicodedata.normalize("NFC", raw)

    # 2. Единый разделитель. Проверки ниже смотрят уже на сегменты.
    text = text.replace("\\", "/")

    if text.startswith("/"):
        # NB (Task 1.4): тоже перекрыта - см. комментарий в _check_segment
        # про пустой сегмент. "/foo".split("/") == ["", "foo"]; ведущий "/"
        # всегда даёт пустой первый сегмент, и он ловится тем же местом.
        raise UnsafePath("путь абсолютный")
    if _utf16_units(text) > MAX_PATH_UTF16:
        raise UnsafePath(f"путь длиннее {MAX_PATH_UTF16} единиц UTF-16")

    segments = text.split("/")
    if len(segments) > MAX_DEPTH:
        raise UnsafePath(f"вложенность больше {MAX_DEPTH}")

    for segment in segments:
        _check_segment(segment)

    return "/".join(segments)


def _check_segment(segment: str) -> None:
    if not segment:
        # Ловит "Photos//img.jpg" (двойной разделитель), а заодно, из-за
        # "".split("/") == [""], и пустой raw целиком, и путь с ведущим "/" -
        # см. пометки Task 1.4 у обеих тех проверок выше по файлу.
        raise UnsafePath("пустой сегмент пути")
    if segment in {".", ".."}:
        # NB (Task 1.4): эта проверка - главное правило против выхода за
        # корень, но при текущем наборе тестов она ПЕРЕКРЫТА проверкой
        # "точка/пробел в конце" ниже: и "." и ".." заканчиваются точкой, так
        # что удаление ОДНОЙ этой строки оставляет сюит зелёным. Мутационный
        # тест обязан удалять обе - иначе он проверяет не то правило, что
        # заявлено. Отдельного теста, различающего эти два правила, при
        # нынешнем наборе не существует.
        raise UnsafePath("сегмент выхода за корень")
    if ":" in segment:
        # NB (Task 1.4): перекрыта - ":" входит и в _FORBIDDEN_CHARACTERS
        # ниже, так что при текущих тестах проверка ниже ловит то же самое
        # значение. Удаление этой строки в одиночку не окрашивает сюит: и
        # "C:evil.exe", и "C:\...", и "file:stream" всё равно падают на
        # forbidden-characters. Ловит и "C:\..." и "C:file" и поток NTFS
        # "file:stream" - все три являются способом уйти не туда, куда
        # получатель разрешил, отдельное сообщение оставлено ради
        # диагностики, а не ради уникальности покрытия.
        raise UnsafePath("двоеточие в имени")
    if segment[-1] in {".", " "}:
        # Windows отбрасывает завершающую точку и пробел, поэтому "a." и "a"
        # столкнулись бы в одном файле, а "a .exe" перестало бы быть тем,
        # что видел пользователь.
        #
        # NB (Task 1.4): эта проверка ПЕРЕКРЫВАЕТ проверку "." / ".." выше -
        # см. её комментарий. Мутационный тест на выход за корень обязан
        # удалить обе, иначе увидит зелёный сюит и решит, что правило
        # отсутствует, хотя на самом деле оно просто заслонено.
        raise UnsafePath("сегмент заканчивается точкой или пробелом")
    if any(character in _FORBIDDEN_CHARACTERS for character in segment):
        raise UnsafePath("запрещённый символ в имени")
    if any(ord(character) < 0x20 for character in segment):
        raise UnsafePath("управляющий символ в имени")
    if any(character in _FORBIDDEN_FORMATTING_CHARACTERS for character in segment):
        raise UnsafePath("управляющий или невидимый символ форматирования текста")
    # .rstrip(" ") - и только ASCII-пробел (0x20), не NBSP (U+00A0): Windows
    # сам отбрасывает завершающий ASCII-пробел перед расширением при разборе
    # DOS-имени устройства, поэтому "NUL .txt" разбирается как "\\.\NUL",
    # измерено через GetFullPathNameW и подтверждено реальным open() (см.
    # §11 спецификации и task-1.2-report.md). "NUL\u00a0.txt" при этом же
    # измерении - обычный файл, поэтому NBSP здесь трогать нельзя: это
    # обычная буква, а не часть разбора устройства.
    stem = segment.split(".", 1)[0].rstrip(" ").upper()
    if stem in _RESERVED_STEMS:
        raise UnsafePath("зарезервированное имя устройства")


#: Больше этого числа записей - уже не операция копирования, а что-то другое.
#: Считает entries И skipped вместе (см. _collision_key ниже про этот же
#: принцип "распространяется на обе стороны"): без skipped в сумме манифест
#: с горсткой настоящих записей и неограниченным skipped обошёл бы именно
#: тот потолок, который существует, чтобы ограничивать работу над
#: недоверенным вводом (round 1 ревью, task-1.3-report.md).
MAX_ENTRIES = 65_536

#: Потолок суммы размеров. 2 ТиБ: больше любого разумного копирования по LAN.
MAX_TOTAL_BYTES = 2 * 1024 ** 4


def _collision_key(path: str) -> str:
    """Ключ для регистронезависимого сравнения - ближе к Windows, чем casefold() сам по себе.

    РАСХОЖДЕНИЕ СТРУКТУРНОЕ И ОТКРЫТОЕ, а не пара измеренных случаев с
    парой неизвестных на будущее (round 3 ревью, task-1.3-report.md).
    NTFS сравнивает регистр по таблице, которая (а) не выходит за пределы
    BMP и (б) заморожена на старой версии Unicode. casefold() - живой,
    полный Unicode-фолдинг, обновляемый каждый релиз. Значит КАЖДАЯ новая
    пара регистра, которую Unicode добавляет для письменности вне старой
    таблицы NTFS, - это новое расхождение, и класс никогда не закроется,
    потому что Unicode продолжает добавлять письменности. Список ниже -
    ОБРАЗЕЦ этого класса, не его граница.

    Измерено реальным open() в свежем временном каталоге на этой машине,
    коллизия подтверждена номером inode, воспроизведено трижды,
    подтверждено целиком через sanitize_manifest (round 1 и round 3
    ревью, task-1.3-report.md):

    - "ß"/"ss"/"SS" - casefold() РАЗВОРАЧИВАЕТ "ß" в "ss" (два символа
      вместо одного), а "ß.txt" и "SS.txt" на диске остаются РАЗНЫМИ
      файлами. Единственная из перечисленных здесь, которую эта функция
      ИСПРАВЛЯЕТ: разворот многосимвольного фолда отключён - если
      casefold() одного символа даёт больше одного символа, символ
      остаётся как есть.
    - Черокки "Ꭰ" (U+13A0, заглавная) / "ꭰ" (U+AB70, строчная) - строчные
      черокки добавлены в Unicode 8.0 (2015), позже заморозки таблицы.
    - Дезерет "𐐀" (U+10400) / "𐐨" (U+10428) - дополнительная плоскость,
      таблица NTFS её не видит вовсе.
    - Грузинская мтаврули "Ა" (U+1C90) / мхедрули "ა" (U+10D0) - мтаврули
      добавлена в Unicode 11.0 (2018).
    - Долгая s "ſ" (U+017F) / "s" - СОВМЕСТИМЫЙ (не канонический) фолд:
      NFC (канонический по определению) его не трогает, а casefold()
      сворачивает.
    - Микро-знак "µ" (U+00B5) / греческая "μ" (U+03BC) - тоже совместимый
      фолд, тоже не тронут NFC.

    Кроме первой ("ß"), все они ОСТАЮТСЯ ложными срабатываниями - и это
    сознательный выбор, а не пробел, который стоит когда-нибудь закрыть.
    Гоняться за точным повторением таблицы NTFS бессмысленно: она не
    выводится из stdlib (upper() расходится в свою сторону - "ı".upper()
    даёт ASCII "I", что ложно свело бы раздельную "ı" с "I", а Windows
    держит их порознь). Два направления ошибки не симметричны: ложное
    срабатывание отказывает МАНИФЕСТ ЦЕЛИКОМ с видимой ошибкой, которую
    пользователь может исправить переименованием одного файла; пропущенная
    коллизия молча пишет две записи в один файл, и вторая затирает первую
    без единого сообщения. Отказ - видимая и обратимая ошибка, пропуск -
    необратимая потеря данных без следа. Пара, различающаяся только одним
    из этих символов, достаточно редка, чтобы цена отказа была приемлемой.

    ЗНАК КЕЛЬВИНА (U+212A), ОМЕГА-ЗНАК (U+2126) и АНГСТРЕМ-ЗНАК (U+212B) -
    НЕ часть этого открытого класса, хотя выглядят похоже и casefold() тоже
    сворачивает каждый из них в обычную строчную букву другого блока
    (ЗНАК КЕЛЬВИНА -> "k", ОМЕГА-ЗНАК -> строчная "ω", АНГСТРЕМ-ЗНАК ->
    строчная "å"). Это здесь неважно - у всех троих КАНОНИЧЕСКОЕ (не
    совместимое) разложение в одну обычную ЗАГЛАВНУЮ букву (K, Ω, Å
    соответственно), и NFC в sanitize_relative_path сворачивает их туда до
    того, как эта функция вообще видит строку. Обе записи в
    паре приходят сюда уже побитово одинаковыми, и отказ манифеста для них -
    правильное поведение (см. в test_paths.py тесты "..._correctly_refused_
    as_the_same_wire_path" для ЗНАКА КЕЛЬВИНА, ОМЕГА-ЗНАКА и
    АНГСТРЕМ-ЗНАКА): специальный случай здесь не нужен и не помог бы -
    раньше в конвейере уже нечего различать.

    Греческая "σ"/"ς" (конечная сигма) и "Σ" - настоящая коллизия на этой
    машине, и casefold() (как и upper()) её ловит без всякого
    специального случая. Раздельная строчная "ı" (без точки) и раздельная
    "İ" (с точкой) уже не путаются с ASCII "I"/"i" под обычным casefold() -
    CaseFolding.txt сознательно не даёт им общего фолда вне турецкой
    локали. Ни то ни другое не требует кода в этой функции.
    """
    return "".join(
        character if len(character.casefold()) != 1 else character.casefold()
        for character in path
    )


def sanitize_manifest(manifest):
    """Манифест с каноническими путями, либо ``UnsafePath`` на весь манифест.

    Отвергается целиком, а не по записям: получивший девять файлов из десяти
    пользователь об этом не узнает, а об отказе узнает.
    """
    from .model import ENTRY_FILE, SkippedEntry, TransferEntry

    if not manifest.entries:
        raise UnsafePath("манифест пуст - нечего предлагать")
    if len(manifest.entries) + len(manifest.skipped) > MAX_ENTRIES:
        raise UnsafePath(f"записей больше {MAX_ENTRIES}")

    total = 0
    seen: dict[str, str] = {}
    entries: list[TransferEntry] = []
    for entry in manifest.entries:
        path = sanitize_relative_path(entry.path)
        key = _collision_key(path)
        if key in seen:
            raise UnsafePath("две записи манифеста столкнулись бы в одном файле")
        seen[key] = path
        if entry.kind == ENTRY_FILE:
            # Только ENTRY_FILE несёт байты на проводе - директория создаётся
            # пустой, без содержимого. Если это когда-нибудь перестанет быть
            # верно (например, у Task 1.5 появится вид записи, который тоже
            # пишет байты), потолок ниже должен считать и его тоже.
            total += entry.size
            if total > MAX_TOTAL_BYTES:
                raise UnsafePath(f"суммарный размер больше {MAX_TOTAL_BYTES}")
        entries.append(
            TransferEntry(path=path, kind=entry.kind, size=entry.size, mtime_ns=entry.mtime_ns)
        )

    skipped = tuple(
        SkippedEntry(path=sanitize_relative_path(skip.path), reason=skip.reason)
        for skip in manifest.skipped
    )

    return type(manifest)(
        transfer_id=manifest.transfer_id,
        entries=tuple(entries),
        skipped=skipped,
        drop_effect=manifest.drop_effect,
    )


